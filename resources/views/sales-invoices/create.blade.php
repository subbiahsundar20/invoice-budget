<script>
document.addEventListener('DOMContentLoaded', function () {
    // Product data is safely generated by Laravel and inserted as JavaScript.
    const products = {{ Illuminate\Support\Js::from($productData) }};

    const body = document.getElementById('items-body');
    const addButton = document.getElementById('add-item');
    let rowIndex = 0;

    function money(value) {
        return '₹' + Number(value || 0).toFixed(2);
    }

    function escapeHtml(value) {
        return String(value).replace(/[&<>"']/g, function (character) {
            return {
                '&': '&amp;',
                '<': '&lt;',
                '>': '&gt;',
                '"': '&quot;',
                "'": '&#039;'
            }[character];
        });
    }

    function addRow(selectedProduct = '', quantity = '1', discount = '0') {
        const row = document.createElement('tr');

        const options = products.map(function (product) {
            const selected = String(product.id) === String(selectedProduct) ? 'selected' : '';
            return `<option value="${product.id}" ${selected}>${escapeHtml(product.name)}</option>`;
        }).join('');

        row.innerHTML = `
            <td>
                <select name="items[${rowIndex}][product_id]" class="form-select product-select" required>
                    <option value="">Select product</option>
                    ${options}
                </select>
            </td>
            <td>
                <input type="number" name="items[${rowIndex}][quantity]"
                       class="form-control quantity-input" value="${quantity}"
                       min="0.01" step="0.01" required>
            </td>
            <td class="unit-price">₹0.00</td>
            <td class="tax-rate">0.00%</td>
            <td>
                <input type="number" name="items[${rowIndex}][discount]"
                       class="form-control discount-input" value="${discount}"
                       min="0" step="0.01" required>
            </td>
            <td class="line-total">₹0.00</td>
            <td>
                <button type="button" class="btn btn-sm btn-outline-danger remove-row">Remove</button>
            </td>
        `;

        body.appendChild(row);
        rowIndex++;
        calculate();
    }

    function calculate() {
        let subtotal = 0;
        let discountTotal = 0;
        let taxTotal = 0;

        body.querySelectorAll('tr').forEach(function (row) {
            const productId = row.querySelector('.product-select').value;
            const product = products.find(function (item) {
                return String(item.id) === String(productId);
            });

            const quantity = Math.max(0, Number(row.querySelector('.quantity-input').value) || 0);
            const discount = Math.max(0, Number(row.querySelector('.discount-input').value) || 0);
            const price = product ? Number(product.price) : 0;
            const taxRate = product ? Number(product.tax_rate) : 0;

            const gross = Math.round(quantity * price * 100) / 100;
            const actualDiscount = Math.min(discount, gross);
            const taxableAmount = Math.max(0, gross - actualDiscount);
            const tax = Math.round(taxableAmount * taxRate) / 100;
            const lineTotal = taxableAmount + tax;

            row.querySelector('.unit-price').textContent = money(price);
            row.querySelector('.tax-rate').textContent = taxRate.toFixed(2) + '%';
            row.querySelector('.line-total').textContent = money(lineTotal);

            subtotal += gross;
            discountTotal += actualDiscount;
            taxTotal += tax;
        });

        subtotal = Math.round(subtotal * 100) / 100;
        discountTotal = Math.round(discountTotal * 100) / 100;
        taxTotal = Math.round(taxTotal * 100) / 100;

        document.getElementById('subtotal').textContent = money(subtotal);
        document.getElementById('discount-total').textContent = money(discountTotal);
        document.getElementById('tax-total').textContent = money(taxTotal);
        document.getElementById('grand-total').textContent = money(subtotal - discountTotal + taxTotal);
    }

    addButton.addEventListener('click', function () {
        addRow();
    });

    body.addEventListener('input', calculate);
    body.addEventListener('change', calculate);

    body.addEventListener('click', function (event) {
        if (event.target.closest('.remove-row')) {
            event.target.closest('tr').remove();
            calculate();
        }
    });

    // Restore old submitted items if validation fails; otherwise start with one row.
    const oldItems = @json(old('items', []));
    if (Array.isArray(oldItems) && oldItems.length > 0) {
        oldItems.forEach(function (item) {
            addRow(item.product_id || '', item.quantity || '1', item.discount || '0');
        });
    } else {
        addRow();
    }
});
</script>
